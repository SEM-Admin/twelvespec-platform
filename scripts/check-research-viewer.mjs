import { chromium } from '@playwright/test';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
import http from 'node:http';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
await mkdir(root+'/.local/research',{recursive:true});
const server=http.createServer(async(req,res)=>{try{if(req.url==='/favicon.ico'){res.writeHead(204);res.end();return;}if(req.url!=='/'){res.writeHead(404);res.end();return;}res.writeHead(200,{'Content-Type':'text/html; charset=utf-8'});res.end(await readFile(root+'/docs/business-research/index.html'));}catch{res.writeHead(500);res.end();}});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const origin='http://127.0.0.1:'+server.address().port;
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-background-networking']});
const page=await browser.newPage({viewport:{width:1280,height:1000}});
const consoleErrors=[],requests=[];let assertionsPassed=0;
page.on('pageerror',e=>consoleErrors.push(e.message));
page.on('console',m=>{if(m.type()==='error')consoleErrors.push(m.text())});
page.on('request',r=>{if(/^https?:/.test(r.url())&&!r.url().startsWith(origin+'/'))requests.push(r.url())});
const ok=(test,note)=>{assert.ok(test,note);assertionsPassed++};
try{
 await page.goto(origin);
 ok((await page.title()).includes('Feature research'),'Research viewer title');
 ok(await page.locator('article').count()===35,'All 35 feature designs load');
 ok((await page.locator('#count').textContent()).includes('35 feature designs'),'Accessible result count');
 await page.getByLabel('Search',{exact:true}).fill('Version-bound proof');
 ok(await page.locator('article').count()===1,'Exact feature search narrows results');
 ok((await page.locator('article h2').textContent()).startsWith('F07'),'Search reaches the correct feature');
 await page.getByText('Rules, edge cases and proposed tests',{exact:true}).click();
 ok(await page.getByText('Editing artwork after approval blocks production release.',{exact:true}).isVisible(),'Rules detail exposes the real failure condition');
 await page.screenshot({path:root+'/.local/research/research-viewer-desktop.png',fullPage:true});
 await page.getByLabel('Search',{exact:true}).fill('');
 await page.getByLabel('Module',{exact:true}).selectOption('stores');
 ok((await page.locator('article').count())>0 && (await page.locator('article').count())<35,'Module filter narrows features');
 ok(await page.getByRole('heading',{name:'F10 · Company-store budgets through checkout',exact:true}).isVisible(),'Store budget feature is present');
 ok(await page.getByRole('heading',{name:'F07 · Version-bound proof and method-specific prepress',exact:true}).count()===0,'Module filtering excludes an unrelated feature');
 await page.getByLabel('Explore',{exact:true}).selectOption('companies');
 ok(await page.getByRole('heading',{name:'OrderMyGear',exact:true}).isVisible(),'Company view retains the relevant store benchmark');
 await page.getByLabel('Module',{exact:true}).selectOption('');
 ok(await page.locator('article').count()===17,'All 17 requested companies are browseable');
 await page.getByLabel('Search',{exact:true}).fill('GotPrint');
 ok(await page.locator('article').count()===1,'Company search works independently');
 ok(await page.locator('article a[href="https://www.gotprint.com/company/info/brokers.html"]').count()===1,'Company evidence links to the primary source');
 await page.getByLabel('Search',{exact:true}).fill('');
 await page.getByLabel('Explore',{exact:true}).selectOption('entities');
 ok(await page.locator('article').count()===30,'Logical data view loads all 30 entities');
 await page.getByLabel('Search',{exact:true}).fill('purchase_submission');
 ok(await page.locator('article').count()===1,'Data-model search selects the purchasing entity');
 await page.getByText('10 field definitions',{exact:true}).click();
 ok(await page.getByRole('cell',{name:'payload_hash',exact:true}).isVisible(),'Field details expose the approval payload binding');
 await page.getByLabel('Explore',{exact:true}).selectOption('features');
 await page.getByLabel('Search',{exact:true}).fill('');
 await page.getByLabel('Module',{exact:true}).selectOption('future');
 ok(await page.locator('article').count()===1,'Coming Soon is a distinct reserved feature pack');
 ok((await page.locator('article').textContent()).includes('COMING_SOON_ONLY'),'Coming Soon status stays explicit');
 ok(await page.locator('article button').count()===0,'Reserved research has no activation button');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:root+'/.local/research/research-viewer-mobile.png',fullPage:true});
 ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'Mobile view has no horizontal document overflow');
 await page.getByLabel('Search',{exact:true}).fill('zz-no-such-feature-zz');
 ok(await page.locator('#empty').isVisible() && await page.locator('article').count()===0,'Empty filter state is useful and truthful');
 await page.getByLabel('Module',{exact:true}).selectOption('');
 await page.getByLabel('Search',{exact:true}).fill('');
 ok(await page.locator('article').count()===35,'Clearing filters restores the full feature inventory');
 await page.getByLabel('Search',{exact:true}).focus();
 ok(await page.getByLabel('Search',{exact:true}).evaluate(e=>e===document.activeElement),'Search remains keyboard focusable');
 ok(requests.length===0,'Viewer makes no external network requests');
 ok(consoleErrors.length===0,'Viewer has no script/console errors');
 const artifactSha256=createHash('sha256').update(await readFile(root+'/docs/business-research/index.html')).digest('hex');
 const evidence={status:'PASS',artifactSha256,checkedAt:new Intl.DateTimeFormat('sv-SE',{timeZone:'America/Chicago',dateStyle:'short',timeStyle:'medium'}).format(new Date()),timezone:'America/Chicago',assertionsPassed,networkRequests:requests.length,consoleErrors,scope:'OFFLINE_RESEARCH_VIEWER_ONLY',screenshots:['.local/research/research-viewer-desktop.png','.local/research/research-viewer-mobile.png']};
 await writeFile(root+'/.local/research/viewer-verification.json',JSON.stringify(evidence,null,2)+'\n');
 process.stdout.write(JSON.stringify(evidence,null,2)+'\n');
}finally{await browser.close();await new Promise(resolve=>server.close(resolve));}
