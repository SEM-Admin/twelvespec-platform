import {test,expect} from '@playwright/test';
import sharp from 'sharp';
import {loginCustomer} from './customer-session';
import {actors} from '../helpers';
import {get,pool,transaction,type Row} from '../../packages/kernel/src';
import {ASSET_STORAGE,assetBytesHash,readStoredAssetBytes} from '../../packages/kernel/src/asset-bytes';
import {readPrivateAsset} from '../../packages/creative/src';

const SHOP='http://localhost:3000';
test.afterAll(async()=>{await pool().end();});
test('customer uploads real artwork, reopens the saved design and retrieves only its durable safe preview',async({page})=>{
 test.setTimeout(90000);
 await loginCustomer(page);
 const {products}=await (await page.request.get(`${SHOP}/api/shop`)).json();
 const product=products.find((item:{title:string})=>item.title==='Classic Camp Cap');
 const marker=`SYNTHETIC DURABLE ${crypto.randomUUID()}`,fileName=`logo-${crypto.randomUUID()}.png`;
 const original=await sharp({create:{width:64,height:32,channels:4,background:'#123456'}}).withMetadata({density:300}).png().toBuffer();
 await page.goto(`${SHOP}/create/${product.id}`,{waitUntil:'networkidle'});
 await page.getByLabel('Your message',{exact:true}).fill(marker);
 await page.getByLabel('I have the right to use this artwork.',{exact:true}).check();
 const uploaded=page.waitForResponse(response=>response.url().endsWith('/api/platform')&&response.request().postDataJSON()?.action==='upload_asset');
 await page.locator('input[type=file]').setInputFiles({name:fileName,mimeType:'image/png',buffer:original});
 const uploadResponse=await uploaded;expect(uploadResponse.ok()).toBe(true);
 const {result:asset}=await uploadResponse.json() as {result:Row};
 await expect(page.getByAltText('Your uploaded artwork',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Save & request proof',exact:true}).click();
 await expect(page.getByRole('status').filter({hasText:'Proof requested for this exact design version'})).toBeVisible();
 await page.reload({waitUntil:'networkidle'});
 await expect(page.getByLabel('Your message',{exact:true})).toHaveValue(marker);
 await expect(page.getByAltText('Your uploaded artwork',{exact:true})).toHaveJSProperty('naturalWidth',64);
 const preview=await page.request.get(`${SHOP}/api/assets/${asset.id}`);
 expect(preview.status()).toBe(200);expect(preview.headers()['cache-control']).toBe('private, no-store');
 const previewBytes=await preview.body();expect((await sharp(previewBytes).metadata()).exif).toBeUndefined();expect(previewBytes.equals(original)).toBe(false);
 const {owner,customer,otherOwner}=await actors();
 const metadata=await transaction(owner,tx=>get(tx,owner,'assets',asset.id));
 expect(metadata.owner_id).toBe(customer.userId);expect(metadata.data.storage).toBe(ASSET_STORAGE);
 expect(assetBytesHash(await transaction(owner,tx=>readStoredAssetBytes(tx,owner,asset.id)))).toBe(assetBytesHash(original));
 expect(metadata.data.productionReadiness).toBe('BLOCKED');expect(metadata.data.scanStatus).toBe('NOT_CONFIGURED');
 await expect(transaction(customer,tx=>readPrivateAsset(tx,customer,asset.id,true))).rejects.toMatchObject({code:'ORIGINAL_DOWNLOAD_REQUIRES_STAFF_REVIEW'});
 await expect(transaction(otherOwner,tx=>readPrivateAsset(tx,otherOwner,asset.id))).rejects.toMatchObject({code:'NOT_FOUND'});
 const internal=await page.request.get(`${SHOP}/api/assets/${metadata.data.previewAssetId}`);expect(internal.status()).toBe(404);
 const account=await (await page.request.get(`${SHOP}/api/shop/account`)).json();
 expect(account.tables.assets.some((item:{id:string})=>item.id===asset.id)).toBe(true);
 expect(account.tables.assets.some((item:{id:string})=>item.id===metadata.data.previewAssetId)).toBe(false);
 expect(JSON.stringify(account.tables.assets)).not.toMatch(/web_bytes|previewAssetId|objectKey|POSTGRES_BYTEA/);
});
